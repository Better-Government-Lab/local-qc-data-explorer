links_of <- function(d, a, b, mode) {
  out <- d %>% group_by(.data[[a]], .data[[b]])
  out <- if (mode == "count") summarise(out, value = n(), .groups = "drop") else summarise(out, value = sum(abs(amount), na.rm = TRUE), .groups = "drop")
  setNames(out, c("source", "target", "value"))
}
order_nodes <- function(...) bind_rows(...) %>% group_by(name) %>% summarise(flow = sum(value), .groups = "drop") %>% arrange(desc(flow)) %>% pull(name)

# Same steps as output$sankeyPlot in app.R
sankey_r <- function(f) {
  d <- df_error %>% filter(year %in% f$years)
  if (isTRUE(f$overThresholdOnly)) d <- d %>% filter(over_threshold == 1)
  if (!is.null(f$state) && f$state != "All States") d <- d %>% filter(State == f$state)
  if (!is.null(f$types))    d <- d %>% filter(Type %in% f$types)
  if (!is.null(f$elements)) d <- d %>% filter(Element %in% f$elements)
  if (!is.null(f$natures))  d <- d %>% filter(Nature %in% f$natures)
  if (!is.null(f$status) && f$status != "All") d <- d %>% filter(Status == f$status)
  dims <- strsplit(f$combination, " → ")[[1]]
  d <- d %>% filter(if_all(all_of(dims), ~ !is.na(.x)))
  pairs <- lapply(seq_len(length(dims) - 1), function(i) links_of(d, dims[i], dims[i + 1], f$mode) %>% filter(value > f$minValue) %>% mutate(step = i))
  columns <- lapply(seq_along(dims), function(i) {
    parts <- list()
    if (i <= length(pairs)) parts <- c(parts, list(pairs[[i]] %>% transmute(name = source, value)))
    if (i > 1)              parts <- c(parts, list(pairs[[i - 1]] %>% transmute(name = target, value)))
    order_nodes(parts)
  })
  list(settings = f,
       columns = columns,
       links = bind_rows(pairs) %>% select(step, source, target, value) %>% arrange(step, source, target))
}
