  client_over_natures = list(years = c(2022, 2023, 2024), state = "All States", status = "Overissuance", overThresholdOnly = FALSE, responsibility = "Client Errors", groupBy = "Error Nature", sortBy = "Number of Cases"),
  texas_technical     = list(years = all_years, state = "Texas", status = "All", overThresholdOnly = TRUE, responsibility = "Technical Errors", groupBy = "Error Element", sortBy = "Average Dollar Amount"))
