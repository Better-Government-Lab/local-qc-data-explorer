# Generates everything the JavaScript viewer takes from R:
#   src/labels.js          code -> label tables and yearly thresholds (from snap-qc-shiny/data-raw/lookups)
#   src/groups.js          grouped choice lists for the element / nature / type filters (from app.R)
#   data/public_data.js    national public QC variances, 2017-2024, as compact code arrays
#   docs/sample/...csv     the downloadable California sample file
#   fixtures/sankey_expected.json, severity_expected.json, pivot_expected.json
#                          what the Shiny app's logic produces for a set of filter settings on each tab
#
# Usage, from the repo root:
#   Rscript tools/build_inputs.R <snap-qc-shiny repo> <folder holding qc_pub_fy<year>.sav>
# Defaults: ../snap-qc-shiny and ../snap_qc/qc_data

suppressMessages({library(dplyr); library(tidyr); library(haven); library(jsonlite)})
args <- commandArgs(trailingOnly = TRUE)
app  <- if (length(args) >= 1) args[1] else "../snap-qc-shiny"
raw  <- if (length(args) >= 2) args[2] else "../snap_qc/qc_data"
years <- 2017:2024   # years of public data bundled with the page
# Error thresholds by fiscal year, from snap_qc/additional_data/year_data.csv. They run past the
# bundled years so that a state's own file for a later year is judged against the right threshold.
thresholds <- c(`2017` = 38, `2018` = 37, `2019` = 37, `2020` = 37, `2021` = 39, `2022` = 48, `2023` = 54, `2024` = 56,
                `2025` = 57, `2026` = 58, `2027` = 59)
num <- function(x) as.numeric(x)
js <- function(name, value, note) paste0("// ", note, " Generated by tools/build_inputs.R. Do not edit by hand.\n",
                                         "export const ", name, " = ", toJSON(value, auto_unbox = TRUE, pretty = TRUE, na = "null"), ";\n")

# ---------------------------------------------------------------- labels
lk <- function(f) read.csv(file.path(app, "data-raw/lookups", f), stringsAsFactors = FALSE)
m  <- function(t, col = "label") as.list(setNames(t[[col]], t[[1]]))
ca <- lk("causes.csv"); has_resp <- !is.na(ca$responsibility) & ca$responsibility != ""
labels <- list(
  elements = m(lk("elements.csv")), natures = m(lk("natures.csv")), causes = m(ca),
  responsibility = as.list(setNames(ca$responsibility[has_resp], ca$code[has_resp])),
  timePeriods = m(lk("time_periods.csv")), verifications = m(lk("verifications.csv")),
  states = m(lk("states.csv"), "state"),
  status = list(`1` = "Amount correct", `2` = "Overissuance", `3` = "Underissuance"),
  caseType = list(`1` = "Certification", `2` = "Recertification"),
  thresholds = as.list(thresholds))
writeLines(js("LABELS", labels, "Code-to-label tables and yearly thresholds."), "src/labels.js", useBytes = TRUE)

# ---------------------------------------------------------------- grouped choice lists, read out of app.R
exprs <- parse(file.path(app, "app.R"))
src <- vapply(exprs, function(e) paste(deparse(e), collapse = "\n"), "")
server_body <- body(eval(exprs[[which(startsWith(src, "server <- function"))[1]]][[3]]))
env <- new.env()
for (e in as.list(server_body)[-1]) {
  if (is.call(e) && identical(e[[1]], as.name("<-")) && is.name(e[[2]]) &&
      as.character(e[[2]]) %in% c("element_choices", "nature_choices", "type_choices")) eval(e, env)
}
as_groups <- function(lst) lapply(setdiff(names(lst), "Select All"), function(g) list(group = g, items = I(unname(lst[[g]]))))
groups <- list(element = as_groups(env$element_choices), nature = as_groups(env$nature_choices), type = as_groups(env$type_choices))
writeLines(js("GROUPS", groups, "Grouped choice lists for the filters, as in the Shiny app."), "src/groups.js", useBytes = TRUE)

# ---------------------------------------------------------------- national public data, compact
# One entry per fiscal year; each field is an array with one value per recorded variance.
#   st state FIPS, fs finding (2 over, 3 under, 1 correct), el element code, na nature code,
#   ca cause code (0 = none), d dollars (AMTERR on the case's first-listed variance, else 0), o over threshold,
#   n 1 on the first-listed variance of a case (a new case starts there), ve verification code (0 = none),
#   tp time period code (0 = none), at action type code (0 = none)
public <- list()
for (y in years) {
  r <- read_sav(file.path(raw, sprintf("qc_pub_fy%d.sav", y)),
                col_select = c("STATE", "STATUS", "AMTERR", "ACTNTYPE", matches("^(ELEMENT|NATURE|AGENCY|VERIF|TIMEPER)[1-9]$")))
  n <- nrow(r)
  v <- bind_rows(lapply(1:9, function(i) tibble(
    case = seq_len(n), slot = i, st = num(r$STATE), fs = num(r$STATUS), amterr = num(r$AMTERR), at = num(r$ACTNTYPE),
    el = num(r[[paste0("ELEMENT", i)]]), na = num(r[[paste0("NATURE", i)]]), ca = num(r[[paste0("AGENCY", i)]]),
    ve = num(r[[paste0("VERIF", i)]]), tp = num(r[[paste0("TIMEPER", i)]])))) %>%
    filter(!is.na(el)) %>% arrange(case, slot) %>%
    group_by(case) %>% mutate(first = slot == min(slot)) %>% ungroup() %>%
    mutate(ca = if_else(is.na(ca) & na %in% 97, 26, ca),
           d = if_else(first & amterr > 0, amterr, 0),
           o = as.integer(amterr > thresholds[[as.character(y)]]))
  public[[as.character(y)]] <- list(st = v$st, fs = v$fs, el = v$el, na = v$na, ca = coalesce(v$ca, 0), d = v$d, o = v$o,
                                    n = as.integer(v$first), ve = coalesce(v$ve, 0), tp = coalesce(v$tp, 0), at = coalesce(v$at, 0))
  cat(y, ":", nrow(v), "variances\n")
}
writeLines(paste0("// National public SNAP QC variances, FY2017-FY2024, as compact code arrays. ",
                  "Generated by tools/build_inputs.R from the public QC files. Do not edit by hand.\n",
                  "export const PUBLIC_DATA = ", toJSON(public, auto_unbox = TRUE), ";\n"), "data/public_data.js", useBytes = TRUE)

