# Same steps as filtered_df() and output$pvt_table in app.R: unique cases by row field and column
# field, with totals that count each case once. A missing value is shown as its own group.
not_recorded <- "(not recorded)"
pivot_fields <- c("Error Responsibility", "Error Type", "Error Nature", "Error Element", "Error Discovery",
                  "Error Timing", "Status of Error Findings", "Case Type", "Year", "State")
verification_all <- bind_rows(lapply(years, function(y) readRDS(file.path(app, sprintf("data/pivot_table_%d.RDS", y))) %>% mutate(Year = y))) %>%
  left_join(flags, by = c("case_id", "Year" = "year")) %>%
  transmute(case = paste(Year, case_id), over_threshold,
            `Error Responsibility` = Responsibility, `Error Type` = Type, `Error Nature` = Nature, `Error Element` = Element,
            `Error Discovery` = if_else(is.na(Verification), "Other", Verification), `Error Timing` = `Time Period`,
            `Status of Error Findings`, `Case Type` = `Action Type`, Year = as.character(Year), State) %>%
  mutate(across(all_of(pivot_fields), ~ coalesce(.x, not_recorded)))
pivot_r <- function(f) {
  d <- verification_all
  for (v in names(f$filters)) d <- d[d[[v]] %in% as.character(f$filters[[v]]), , drop = FALSE]
  if (isTRUE(f$overThresholdOnly)) d <- d %>% filter(over_threshold == 1)
  d <- d %>% transmute(case, row = .data[[f$rows]], col = .data[[f$cols]])
  list(settings = f,
       cells = d %>% group_by(row, col) %>% summarise(n = n_distinct(case), .groups = "drop"),
       rowTotals = d %>% group_by(row) %>% summarise(n = n_distinct(case), .groups = "drop"),
       colTotals = d %>% group_by(col) %>% summarise(n = n_distinct(case), .groups = "drop"),
       total = n_distinct(d$case))
}
pivot_settings <- list(
  default_view      = list(rows = "Error Type", cols = "Error Discovery", overThresholdOnly = TRUE, filters = setNames(list(), character(0))),
  michigan_by_year  = list(rows = "Error Element", cols = "Year", overThresholdOnly = TRUE, filters = list(State = I("Michigan"))),
  timing_by_case    = list(rows = "Error Timing", cols = "Case Type", overThresholdOnly = FALSE,
                           filters = list(Year = c("2023", "2024"), `Status of Error Findings` = I("Overissuance"))),
  state_by_resp     = list(rows = "State", cols = "Error Responsibility", overThresholdOnly = TRUE,
                           filters = list(`Error Timing` = c("Before most recent action", not_recorded), Year = c("2019", "2022"))))
write_json(lapply(pivot_settings, pivot_r), "fixtures/pivot_expected.json", auto_unbox = TRUE, digits = NA, null = "null")
