# Same steps as output$errorDollarPlot in app.R. Cases with no dollar amount and rows with no label
# for the grouping field are left out.
severity_r <- function(f) {
  d <- df_error %>% mutate(resp = unname(resp_of[Type])) %>% filter(year %in% f$years)
  if (isTRUE(f$overThresholdOnly)) d <- d %>% filter(over_threshold == 1)
  if (f$state != "All States") d <- d %>% filter(State == f$state)
  if (f$status != "All") d <- d %>% filter(Status == f$status)
  if (f$responsibility != "All") d <- d %>% filter(resp == f$responsibility)
  g <- c(`Error Type` = "Type", `Error Nature` = "Nature", `Error Element` = "Element")[[f$groupBy]]
  out <- d %>% filter(!is.na(amount), !is.na(.data[[g]])) %>%
    select(year, case_id, group = all_of(g), amount) %>% distinct() %>%
    group_by(group) %>% summarise(avg = mean(amount), n = n_distinct(paste(year, case_id)), .groups = "drop")
  out <- if (f$sortBy == "Average Dollar Amount") arrange(out, desc(avg)) else arrange(out, desc(n))
  list(settings = f, groups = out)
}
